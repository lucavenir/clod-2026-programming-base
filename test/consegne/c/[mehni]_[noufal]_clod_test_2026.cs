List<string> AnonymizeUserIds(List<int> userIds)
{
    var result=[];
    for(var i=0; i<userIds.length;i++)
    {
        if(userIds.length(i)>= 5000)
        {
            result.Add(userIds.length(i));
        }
        return "ANONYMOUS";
    }

return result;
    
}    


